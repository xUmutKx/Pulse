/// `c` without its accent, or `c` itself.
pub fn bare(c: u16) -> u16 {
    if c < 0x00C0 {
        return c;
    }
    match TABLE.binary_search_by_key(&c, |&(a, _)| a) {
        Ok(i) => TABLE[i].1,
        Err(_) => c,
    }
}

/// Whether `label` is `typed` with an accent the typist left off.
pub fn is_accent_of(label: u16, typed: u16) -> bool {
    label != typed && label >= 0x00C0 && bare(label) == typed
}

